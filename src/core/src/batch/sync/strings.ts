/** 取文案并调用（值可为模板函数或纯字符串；locale 非法回退 zh）。 */
export const syncMsg = (locale: SyncLocale, key: string, ...args: any[]): string => {
    const v = (SYNC_MSG[locale] ?? SYNC_MSG.zh)[key] ?? SYNC_MSG.zh[key] ?? key;
    return typeof v === "function" ? v(...args) : v;
};
