/** 按访问时 state.locale 分发的文案代理（zh 缺键回退 en→zh→键名）。 */
export const S = new Proxy(
  {},
  {
    get: (_t, key) => {
      const dict = state.locale === "en" ? EN : ZH;
      const v = dict[key] ?? ZH[key];
      if (v == null) {
        console.warn("[strings] missing key:", String(key));
        return String(key);
      }
      return v;
    },
  }
);
